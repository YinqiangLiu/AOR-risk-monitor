CREATE VIEW AOR_RISK.ANALYTICS.V_RETURNS AS
WITH previous_prices AS (
    SELECT
        TRADE_DATE,
        TICKER,
        ADJUSTED_CLOSE,
        LAG(ADJUSTED_CLOSE) OVER (
            PARTITION BY TICKER
            ORDER BY TRADE_DATE
        ) AS PREVIOUS_CLOSE
    FROM AOR_RISK.RAW.PRICES
)
SELECT
    TRADE_DATE,
    TICKER,
    ADJUSTED_CLOSE,
    ADJUSTED_CLOSE / NULLIF(PREVIOUS_CLOSE, 0) - 1
        AS DAILY_RETURN
FROM previous_prices;


SELECT
    TRADE_DATE,
    TICKER,
    ADJUSTED_CLOSE,
    ROUND(DAILY_RETURN * 100, 4) AS DAILY_RETURN_PERCENT
FROM AOR_RISK.ANALYTICS.V_RETURNS
WHERE TICKER = 'AOR'
ORDER BY TRADE_DATE
LIMIT 10;


SELECT
    TICKER,
    COUNT(*) AS PRICE_OBSERVATIONS,
    COUNT(DAILY_RETURN) AS RETURN_OBSERVATIONS
FROM AOR_RISK.ANALYTICS.V_RETURNS
GROUP BY TICKER
ORDER BY TICKER;