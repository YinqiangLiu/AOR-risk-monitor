-- Risk Contribution Model
-- Estimate volatility contributions from current holdings
CREATE VIEW AOR_RISK.ANALYTICS.V_RISK_CONTRIBUTIONS AS
WITH holdings AS (
    SELECT * FROM AOR_RISK.ANALYTICS.V_CURRENT_HOLDINGS
    WHERE PORTFOLIO_ID = 'AOR'
),
asset_returns AS (
    SELECT h.TICKER, h.WEIGHT, r.TRADE_DATE, r.DAILY_RETURN
    FROM holdings h
    JOIN AOR_RISK.ANALYTICS.V_RETURNS r
        ON h.TICKER = r.TICKER
    WHERE h.ASSET_CLASS <> 'Cash'
      AND r.DAILY_RETURN IS NOT NULL
      AND r.TRADE_DATE BETWEEN
          (SELECT MIN(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y)
          AND
          (SELECT MAX(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y)),
model_returns AS (
    SELECT
        TRADE_DATE,
        SUM(WEIGHT * DAILY_RETURN) AS MODEL_RETURN
    FROM asset_returns
    GROUP BY TRADE_DATE

    -- Require exactly one return for every non-cash holding
    HAVING COUNT(*) = COUNT(DISTINCT TICKER)
       AND COUNT(*) = (
           SELECT COUNT(*)
           FROM holdings
           WHERE ASSET_CLASS <> 'Cash'
       )
),
portfolio_risk AS (
    SELECT
        COUNT(*) AS OBSERVATIONS,
        VAR_SAMP(MODEL_RETURN) AS PORTFOLIO_VARIANCE
    FROM model_returns
),
covariances AS (
    SELECT a.TICKER, COVAR_SAMP(a.DAILY_RETURN, p.MODEL_RETURN) AS COV_WITH_MODEL
    FROM asset_returns a
    JOIN model_returns p
        ON a.TRADE_DATE = p.TRADE_DATE
    GROUP BY a.TICKER
)
SELECT h.PORTFOLIO_ID, h.HOLDINGS_DATE, h.TICKER, h.ASSET_CLASS, h.WEIGHT, pr.OBSERVATIONS,
    SQRT(pr.PORTFOLIO_VARIANCE) * SQRT(252)
        AS MODEL_ANNUALIZED_VOLATILITY,
    CASE
        WHEN h.ASSET_CLASS = 'Cash' THEN 0
        ELSE
            h.WEIGHT * c.COV_WITH_MODEL
            / NULLIF(pr.PORTFOLIO_VARIANCE, 0)
    END AS RISK_SHARE

FROM holdings h
CROSS JOIN portfolio_risk pr
LEFT JOIN covariances c
    ON h.TICKER = c.TICKER;



--Display each holding's estimated risk share
SELECT
    TICKER,
    ASSET_CLASS,
    ROUND(WEIGHT * 100, 2) AS WEIGHT_PERCENT,
    ROUND(RISK_SHARE * 100, 2) AS RISK_SHARE_PERCENT,
    OBSERVATIONS
FROM AOR_RISK.ANALYTICS.V_RISK_CONTRIBUTIONS
ORDER BY RISK_SHARE DESC;

-- Check completeness and contribution totals
SELECT
    COUNT(*) AS HOLDINGS_COUNT,
    COUNT(RISK_SHARE) AS CALCULATED_RISK_SHARES,
    MIN(OBSERVATIONS) AS MODEL_DAYS,
    ROUND(SUM(WEIGHT) * 100, 2) AS TOTAL_WEIGHT_PERCENT,
    ROUND(SUM(RISK_SHARE) * 100, 4) AS TOTAL_RISK_SHARE_PERCENT,
    ROUND(MAX(MODEL_ANNUALIZED_VOLATILITY) * 100, 2)
        AS MODEL_VOLATILITY_PERCENT
FROM AOR_RISK.ANALYTICS.V_RISK_CONTRIBUTIONS;