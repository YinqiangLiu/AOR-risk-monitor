SELECT
    COUNT(*) AS HOLDINGS_ROWS,
    COUNT(DISTINCT TICKER) AS UNIQUE_TICKERS,
    ROUND(SUM(WEIGHT) * 100, 2) AS TOTAL_WEIGHT_PERCENT,
    MIN(HOLDINGS_DATE) AS FIRST_HOLDINGS_DATE,
    MAX(HOLDINGS_DATE) AS LAST_HOLDINGS_DATE
FROM AOR_RISK.RAW.HOLDINGS;


SELECT
    'DUPLICATE_PRICE_KEYS' AS CHECK_NAME,
    COUNT(*) AS PROBLEM_COUNT
FROM (
    SELECT TICKER, TRADE_DATE
    FROM AOR_RISK.RAW.PRICES
    GROUP BY TICKER, TRADE_DATE
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'INVALID_PRICES',
    COUNT(*)
FROM AOR_RISK.RAW.PRICES
WHERE TRADE_DATE IS NULL
   OR TICKER IS NULL
   OR TRIM(TICKER) = ''
   OR ADJUSTED_CLOSE IS NULL
   OR ADJUSTED_CLOSE <= 0

UNION ALL

SELECT
    'DATES_WITHOUT_ALL_8_ETFS',
    COUNT(*)
FROM (
    SELECT TRADE_DATE
    FROM AOR_RISK.RAW.PRICES
    GROUP BY TRADE_DATE
    HAVING COUNT(DISTINCT TICKER) <> 8
);