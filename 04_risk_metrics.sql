CREATE VIEW AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y AS
SELECT
    TRADE_DATE,
    TICKER,
    ADJUSTED_CLOSE,
    DAILY_RETURN
FROM AOR_RISK.ANALYTICS.V_RETURNS
WHERE TICKER = 'AOR'
  AND DAILY_RETURN IS NOT NULL
  AND TRADE_DATE >= DATEADD(
      year,
      -3,
      (
          SELECT MAX(TRADE_DATE)
          FROM AOR_RISK.RAW.PRICES
          WHERE TICKER = 'AOR'
      )
  );



  CREATE VIEW AOR_RISK.ANALYTICS.V_FUND_RISK_3Y AS
WITH risk_statistics AS (
    SELECT
        MIN(TRADE_DATE) AS PERIOD_START,
        MAX(TRADE_DATE) AS PERIOD_END,
        COUNT(*) AS OBSERVATIONS,

        STDDEV_SAMP(DAILY_RETURN) * SQRT(252)
            AS ANNUALIZED_VOLATILITY,

        PERCENTILE_CONT(0.05)
            WITHIN GROUP (ORDER BY DAILY_RETURN)
            AS RETURN_Q05

    FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y
),
tail_losses AS (
    SELECT
        -AVG(f.DAILY_RETURN) AS EXPECTED_SHORTFALL_95_1D
    FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y f
    CROSS JOIN risk_statistics r
    WHERE f.DAILY_RETURN <= r.RETURN_Q05
)
SELECT
    r.PERIOD_START,
    r.PERIOD_END,
    r.OBSERVATIONS,
    r.ANNUALIZED_VOLATILITY,
    -r.RETURN_Q05 AS VAR_95_1D,
    t.EXPECTED_SHORTFALL_95_1D
FROM risk_statistics r
CROSS JOIN tail_losses t;



SELECT
    PERIOD_START,
    PERIOD_END,
    OBSERVATIONS,

    ROUND(ANNUALIZED_VOLATILITY * 100, 2)
        AS ANNUALIZED_VOLATILITY_PERCENT,

    ROUND(VAR_95_1D * 100, 2)
        AS DAILY_VAR_95_PERCENT,

    ROUND(EXPECTED_SHORTFALL_95_1D * 100, 2)
        AS DAILY_ES_95_PERCENT

FROM AOR_RISK.ANALYTICS.V_FUND_RISK_3Y;