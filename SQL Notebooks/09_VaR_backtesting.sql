-- Create the rolling forecasts and flag exceptions
 -- Estimate each day's VaR using only earlier returns
CREATE VIEW AOR_RISK.ANALYTICS.V_VAR_BACKTEST AS
WITH aor_returns AS (
    SELECT
        TRADE_DATE,
        DAILY_RETURN,
        ROW_NUMBER() OVER (
            ORDER BY TRADE_DATE
        ) AS ROW_NUM
    FROM AOR_RISK.ANALYTICS.V_RETURNS
    WHERE TICKER = 'AOR'
      AND DAILY_RETURN IS NOT NULL
),
forecasts AS (
    SELECT
        t.TRADE_DATE,
        t.DAILY_RETURN,
        COUNT(*) AS TRAINING_DAYS,

        PERCENTILE_CONT(0.05)
            WITHIN GROUP (ORDER BY h.DAILY_RETURN)
            AS RETURN_Q05

    FROM aor_returns t
    JOIN aor_returns h
        ON h.ROW_NUM BETWEEN t.ROW_NUM - 252
                         AND t.ROW_NUM - 1

    GROUP BY
        t.TRADE_DATE,
        t.DAILY_RETURN

    HAVING COUNT(*) = 252
)
SELECT
    TRADE_DATE,
    DAILY_RETURN,
    TRAINING_DAYS,
    -RETURN_Q05 AS VAR_95_1D,

    CASE
        WHEN DAILY_RETURN < RETURN_Q05 THEN 1
        ELSE 0
    END AS EXCEPTION_FLAG

FROM forecasts;


--Summarize the backtest
SELECT
    MIN(TRADE_DATE) AS PERIOD_START,
    MAX(TRADE_DATE) AS PERIOD_END,
    COUNT(*) AS BACKTEST_DAYS,
    SUM(EXCEPTION_FLAG) AS VAR_EXCEPTIONS,

    ROUND(AVG(EXCEPTION_FLAG) * 100, 2)
        AS EXCEPTION_RATE_PERCENT,

    5.00 AS TARGET_EXCEPTION_RATE_PERCENT

FROM AOR_RISK.ANALYTICS.V_VAR_BACKTEST

WHERE TRADE_DATE BETWEEN
    (SELECT MIN(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y)
    AND
    (SELECT MAX(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y);
    
-- Inspect days when losses exceeded forecast VaR

SELECT TRADE_DATE,
    ROUND(-DAILY_RETURN * 100, 2)
        AS REALIZED_LOSS_PERCENT,
    ROUND(VAR_95_1D * 100, 2)
        AS FORECAST_VAR_PERCENT,
    TRAINING_DAYS

FROM AOR_RISK.ANALYTICS.V_VAR_BACKTEST

WHERE EXCEPTION_FLAG = 1
  AND TRADE_DATE >= (
      SELECT MIN(TRADE_DATE)
      FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y
  )

ORDER BY TRADE_DATE DESC
LIMIT 20;



-- Summarize the complete three-year evaluation period
SELECT
    MIN(TRADE_DATE) AS PERIOD_START,
    MAX(TRADE_DATE) AS PERIOD_END,
    COUNT(*) AS BACKTEST_DAYS,
    SUM(EXCEPTION_FLAG) AS VAR_EXCEPTIONS,
    ROUND(AVG(EXCEPTION_FLAG) * 100, 2)
        AS EXCEPTION_RATE_PERCENT,
    5.00 AS TARGET_EXCEPTION_RATE_PERCENT
FROM AOR_RISK.ANALYTICS.V_VAR_BACKTEST
WHERE TRADE_DATE BETWEEN
    (SELECT MIN(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y)
    AND
    (SELECT MAX(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y);