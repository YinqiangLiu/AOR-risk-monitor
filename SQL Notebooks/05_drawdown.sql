--Calculate daily drawdowns
CREATE VIEW AOR_RISK.ANALYTICS.V_FUND_DRAWDOWN_3Y AS
WITH baseline AS (
    SELECT ADJUSTED_CLOSE AS BASELINE_CLOSE
    FROM AOR_RISK.RAW.PRICES
    WHERE TICKER = 'AOR'
      AND TRADE_DATE < (SELECT MIN(TRADE_DATE) FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y)
    QUALIFY ROW_NUMBER() OVER (
        ORDER BY TRADE_DATE DESC
    ) = 1
)
SELECT f.TRADE_DATE, f.ADJUSTED_CLOSE, f.ADJUSTED_CLOSE / GREATEST(
        b.BASELINE_CLOSE,
        MAX(f.ADJUSTED_CLOSE) OVER (
            ORDER BY f.TRADE_DATE
            ROWS BETWEEN UNBOUNDED PRECEDING
                     AND CURRENT ROW
        )
    ) - 1 AS DRAWDOWN

FROM AOR_RISK.ANALYTICS.V_FUND_RETURNS_3Y f
CROSS JOIN baseline b;


--Drawdown = (current adjusted price / Highest adjusted price so far) - 1
-- Find the max drawdown
SELECT
    TRADE_DATE AS TROUGH_DATE,
    ROUND(DRAWDOWN * 100, 2)
        AS MAX_DRAWDOWN_PERCENT
FROM AOR_RISK.ANALYTICS.V_FUND_DRAWDOWN_3Y
ORDER BY DRAWDOWN ASC, TRADE_DATE ASC
LIMIT 1;