--Select the latest holdings
CREATE VIEW AOR_RISK.ANALYTICS.V_CURRENT_HOLDINGS AS
SELECT * FROM AOR_RISK.RAW.HOLDINGS
QUALIFY HOLDINGS_DATE = MAX(HOLDINGS_DATE) OVER (
    PARTITION BY PORTFOLIO_ID
);

--Calculate exposure by asset class
CREATE VIEW AOR_RISK.ANALYTICS.V_EXPOSURES AS
SELECT
    PORTFOLIO_ID,
    HOLDINGS_DATE,
    ASSET_CLASS,
    SUM(WEIGHT) AS PORTFOLIO_WEIGHT,
    SUM(MARKET_VALUE) AS MARKET_VALUE_USD
FROM AOR_RISK.ANALYTICS.V_CURRENT_HOLDINGS
GROUP BY
    PORTFOLIO_ID,
    HOLDINGS_DATE,
    ASSET_CLASS;

--Display the exposure report
SELECT
    HOLDINGS_DATE,
    ASSET_CLASS,
    ROUND(PORTFOLIO_WEIGHT * 100, 2) AS WEIGHT_PERCENT,
    ROUND(MARKET_VALUE_USD, 2) AS MARKET_VALUE_USD
FROM AOR_RISK.ANALYTICS.V_EXPOSURES
ORDER BY PORTFOLIO_WEIGHT DESC;