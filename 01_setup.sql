CREATE WAREHOUSE AOR_RISK_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

USE WAREHOUSE AOR_RISK_WH;
CREATE DATABASE AOR_RISK;

CREATE SCHEMA AOR_RISK.RAW;
CREATE SCHEMA AOR_RISK.ANALYTICS;

CREATE TABLE AOR_RISK.RAW.PRICES (TRADE_DATE DATE, TICKER VARCHAR, ADJUSTED_CLOSE DOUBLE, SOURCE VARCHAR);

CREATE TABLE AOR_RISK.RAW.HOLDINGS (PORTFOLIO_ID VARCHAR, HOLDINGS_DATE DATE, TICKER VARCHAR, SECURITY_NAME VARCHAR, ASSET_CLASS VARCHAR, WEIGHT DOUBLE, MARKET_VALUE DOUBLE, CURRENCY VARCHAR);

CREATE TABLE AOR_RISK.ANALYTICS.DEMO_LIMITS (RULE_NAME VARCHAR, THRESHOLD DOUBLE);

